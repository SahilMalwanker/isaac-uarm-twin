def preview_sheet(items, times, size, path, scale=0.5, columns=4, labels=()):
    from PIL import Image, ImageDraw

    tiles = []
    for t in times:
        img = Image.new("RGB", (int(size[0] * scale), int(size[1] * scale)), BG)
        draw = ImageDraw.Draw(img)
        for item in items:
            item.pil(draw, t, scale)
        for x, y, label, *_ in labels:
            draw.text((x * scale, y * scale - 8), label.replace("&#8594;", ">").replace("&#8592;", "<"), fill=GREY2)
        draw.text((8, 6), f"t={t:5.2f}s", fill=GREEN)
        tiles.append(img)
    rows = math.ceil(len(tiles) / columns)
    width, height = tiles[0].size
    sheet = Image.new("RGB", (columns * width + (columns - 1) * 4, rows * height + (rows - 1) * 4), "#333333")
    for i, tile in enumerate(tiles):
        sheet.paste(tile, ((i % columns) * (width + 4), (i // columns) * (height + 4)))
    path.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(path)
    return path


def write(name, content):
    path = (OUT if name == "architecture.svg" else PREVIEWS) / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT).as_posix()} ({len(content.encode('utf-8')) // 1024} KiB)")


