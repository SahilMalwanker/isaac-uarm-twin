class Item:
    """An SVG path whose geometry, colour and opacity may change per frame.

    ``kind`` is "line" (stroked polylines), "shape" (filled polygons) or "dots" (round dots);
    ``geom`` is a list of point lists or a function of time returning one.
    """

    def __init__(self, kind, geom, stroke=None, fill=None, width=1.0, color=None, opacity=None, alpha=1.0,
                 dash=None):
        self.kind, self.geom, self.stroke, self.fill, self.width = kind, geom, stroke, fill, width
        self.color, self.opacity, self.alpha, self.dash = color, opacity, alpha, dash

    def at(self, t):
        return self.geom(t) if callable(self.geom) else self.geom

    def svg(self, frames, dur):
        animated = callable(self.geom)
        ds = [path_d(self.kind, self.at(t)) for t in (frames if animated else [0.0])]
        if self.kind == "shape":
            attrs = [f'fill="{self.fill}"', f'stroke="{self.stroke}" stroke-width="{self.width:g}" stroke-linejoin="round"'
                     if self.stroke else 'stroke="none"']
        else:
            attrs = [f'fill="none" stroke="{self.stroke}" stroke-width="{self.width:g}" stroke-linecap="round" '
                     'stroke-linejoin="round"']
        if self.alpha < 1.0:
            attrs.append(f'{"fill" if self.kind == "shape" else "stroke"}-opacity="{self.alpha:g}"')
        if self.dash:
            attrs.append(f'stroke-dasharray="{self.dash}"')
        anims = [smil("d", ds, dur)] if animated else []
        if self.color:
            attr = "fill" if self.kind == "shape" else "stroke"
            anims.append(smil(attr, [self.color(t) for t in frames], dur, discrete=True))
        if self.opacity:
            values = [f"{self.opacity(t):.2f}" for t in frames]
            attrs.append(f'opacity="{values[0]}"')
            anims.append(smil("opacity", values, dur))
        body = "".join(anims)
        return f'<path d="{ds[0]}" {" ".join(attrs)}>{body}</path>' if body else f'<path d="{ds[0]}" {" ".join(attrs)}/>'

    def pil(self, draw, t, k):
        opacity = self.opacity(t) if self.opacity else 1.0
        if opacity < 0.05:
            return
        colour = self.color(t) if self.color else (self.fill if self.kind == "shape" else self.stroke)
        colour = mix(colour, BG, self.alpha * opacity) if colour not in (None, "none") else colour
        for line in self.at(t):
            pts = [(x * k, y * k) for x, y in line]
            if self.kind == "shape":
                if colour == "none":
                    draw.line(pts + pts[:1], fill=self.stroke, width=max(1, round(self.width * k)))
                else:
                    draw.polygon(pts, fill=colour, outline=self.stroke)
            elif self.kind == "dots":
                r = self.width * k / 2
                draw.ellipse([pts[0][0] - r, pts[0][1] - r, pts[0][0] + r, pts[0][1] + r], fill=colour)
            else:
                draw.line(pts, fill=colour, width=max(1, round(self.width * k)), joint="curve")


def mix(colour, background, alpha):
    a = [int(colour[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(background[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(y + (x - y) * alpha):02x}" for x, y in zip(a, b))


def path_d(kind, polylines):
    if kind == "dots":
        return "".join(f"M{line[0][0]:.1f} {line[0][1]:.1f}l0 0" for line in polylines)
    close = "Z" if kind == "shape" else ""
    return "".join("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in line) + close for line in polylines)


def smil(attr, values, dur, discrete=False, translate=False):
    """SMIL animation over evenly spaced frames; static stretches collapse into keyTimes."""
    n = len(values) - 1
    keep = [0]
    for i in range(1, n):
        if discrete:
            if values[i] != values[keep[-1]]:
                keep.append(i)
        elif not values[i - 1] == values[i] == values[i + 1]:
            keep.append(i)
    keep.append(n)
    if all(values[i] == values[0] for i in keep):
        return ""
    times = ";".join("0" if i == 0 else "1" if i == n else f"{i / n:.4f}" for i in keep)
    mode = ' calcMode="discrete"' if discrete else ""
    head = ('<animateTransform attributeName="transform" type="translate"' if translate
            else f'<animate attributeName="{attr}"')
    return (f'{head} dur="{dur:g}s" repeatCount="indefinite"{mode} keyTimes="{times}" '
            f'values="{";".join(values[i] for i in keep)}"/>')


def text(x, y, value, size=12, fill=WHITE, anchor="start", mono=False, weight=None, spacing=None, child="",
         hidden=False):
    family = f' font-family="{MONO}"' if mono else ""
    bold = f' font-weight="{weight}"' if weight else ""
    track = f' letter-spacing="{spacing}"' if spacing else ""
    opacity = ' opacity="0"' if hidden else ""
    return (f'<text x="{x:.1f}" y="{y:.1f}" text-anchor="{anchor}"{family} font-size="{size}"{bold}{track} '
            f'fill="{fill}"{opacity}>{value}{child}</text>')


def windows(start, end, dur):
    """Discrete opacity animation: visible between ``start`` and ``end`` seconds."""
    times, values = ["0"], ["1" if start <= 0 else "0"]
    if start > 0:
        times.append(f"{start / dur:.4f}")
        values.append("1")
    if end < dur:
        times.append(f"{end / dur:.4f}")
        values.append("0")
    return (f'<animate attributeName="opacity" dur="{dur:g}s" repeatCount="indefinite" calcMode="discrete" '
            f'keyTimes="{";".join(times)}" values="{";".join(values)}"/>')


def frame_times(dur, fps):
    n = max(2, round(dur * fps))
    return [i * dur / n for i in range(n + 1)]


def ease(u):
    u = min(max(u, 0.0), 1.0)
    return u * u * (3.0 - 2.0 * u)


def lerp(a, b, u):
    return tuple(x + (y - x) * u for x, y in zip(a, b))


def interp(keys, t):
    """Eased interpolation through ``(time, value)`` keys; values are tuples or floats."""
    if t <= keys[0][0]:
        return keys[0][1]
    for (t0, a), (t1, b) in zip(keys, keys[1:]):
        if t0 <= t <= t1:
            if t1 - t0 < 1e-9:
                return b
            u = ease((t - t0) / (t1 - t0))
            return lerp(a, b, u) if isinstance(a, tuple) else a + (b - a) * u
    return keys[-1][1]


