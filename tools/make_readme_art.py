def plane_keys(step_lists, seconds=1.1):
    """Tool-point keys (reach, z) in the arm's own plane through real waypoints, looping back to the start."""
    points = []
    for steps in step_lists:
        for p in waypoints(steps):
            point = (round(math.hypot(p[0], p[1]), 1), float(p[2]))
            if point not in points:
                points.append(point)
    keys = [(i * seconds, point) for i, point in enumerate(points)]
    return keys + [(len(points) * seconds, points[0])]


def plane_joints(point):
    return kinematics.joints_from_motors(*kinematics.motor_angles(point[0], 0.0, point[1]))[1:]


def side_pose(origin, scale):
    cache = {}

    def pose(joints):
        key = tuple(round(j, 4) for j in joints)
        if key not in cache:
            sol = kinematics.solve_linkage(*joints)["points"]

            def to(q):
                return origin[0] + scale * q[0], origin[1] - scale * q[1]

            pts = {k: to(v) for k, v in sol.items()}
            pts["corner"] = to((sol["tool"][0], sol["wrist"][1]))
            cache[key] = pts
        return cache[key]

    return pose


