def hero_items():
    """Plant arm (telemetry source) and twin arm (1 Hz samples, smoothed every 60 Hz step) in side view."""
    keys = plane_keys((sequences.ARM1_SEQ1[:16],), seconds=1.5)
    dur = keys[-1][0]
    hz, cache = 60.0, {}

    def plant(t):
        key = round(t, 4)
        if key not in cache:
            cache[key] = plane_joints(interp(keys, t))
        return cache[key]

    twin, smooth = [], None
    for loop in range(2):
        for i in range(int(round(dur * hz))):
            target = plant(float(math.floor(i / hz)))
            smooth = target if smooth is None else tuple(a + follower.ALPHA * (b - a) for a, b in zip(smooth, target))
            if loop:
                twin.append(smooth)

    def twin_at(t):
        return twin[min(len(twin) - 1, round(t * hz))]

    plant_pose, twin_pose = side_pose((842, 238), 420), side_pose((1040, 238), 420)
    items = []
    for x in (842, 1040):
        items.append(Item("shape", [[(x - 20, 238), (x + 20, 238), (x + 20, 300), (x - 20, 300)]], fill="#141414"))
