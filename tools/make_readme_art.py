def follow(cycle, arm, joint, servo_index, hz=60.0, telemetry_hz=1.0):
    """(t, applied target, mapped sample) of the follower, simulated with its own functions (warm second loop)."""
    cfg = follower.ARM_CONFIGS[arm]
    dt, steps = 1.0 / hz, int(round(cycle.T * hz))
    out, smooth, applied = [], None, None
    for loop in range(2):
        for i in range(steps):
            tau = i * dt
            servo = cycle.servo(arm, math.floor(tau * telemetry_hz) / telemetry_hz)[servo_index]
            target = follower.servo_to_isaac_deg(cfg, joint, servo)
            limited = follower.rate_limit(smooth, target, cfg["rate_limit_deg_per_s"][joint], dt)
            smooth = limited if smooth is None else smooth + follower.ALPHA * (limited - smooth)
            if applied is None or abs(smooth - applied) >= follower.DEADBAND_DEG:
                applied = smooth
            if loop:
                out.append((tau, applied, target))
    return out


