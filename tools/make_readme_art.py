MOVE_SPEED, CATCH_SPEED = 0.40, 0.15  # m/s - animation pacing; the cell itself runs slower
MIN_SEGMENT, WAIT_SCALE = 0.3, 0.3
BELT_SPEED = 0.25  # m/s - animation pacing; the scene belts run at 0.15 m/s
CYCLE_FPS = 10


def waypoints(steps, kind=None):
    return [tuple(v) for k, v in steps if k in ("move", "catch") and (kind is None or k == kind)]


class ArmTrack:
    """Tool point (SDK millimetres) and wrist angle of one arm over time."""

    def __init__(self, robot, start, wrist=90.0):
        self.base, self.yaw = robot["base"], robot["yaw"]
        self.keys = [(0.0, start)]
        self.wrist_keys = [(0.0, wrist)]
        self.arrivals, self.events = [], []
        self.t = 0.0

    def run(self, steps, start_time):
        self.t = max(self.t, start_time)
        for kind, value in steps:
            if kind in ("move", "catch"):
                previous = self.keys[-1][1]
                self.keys.append((self.t, previous))
                distance = math.dist(previous, value) / 1000.0
                self.t += max(MIN_SEGMENT, distance / (MOVE_SPEED if kind == "move" else CATCH_SPEED))
                self.keys.append((self.t, tuple(value)))
                self.arrivals.append((self.t, tuple(value)))
            elif kind == "wait":
                self.t += value * WAIT_SCALE
            else:
                if kind == "wrist":
                    self.wrist_keys += [(self.t, self.wrist_keys[-1][1]), (self.t + 0.4, float(value))]
                self.events.append((self.t, kind, value))
        return self.t

    def sdk(self, t):
        return interp(self.keys, t)

    def wrist(self, t):
        return interp(self.wrist_keys, t)

    def arrival(self, point, after=-1.0):
        return next(t for t, p in self.arrivals if p == tuple(point) and t > after)

    def event(self, kind, value, after=-1.0):
        return next(t for t, k, v in self.events if k == kind and v == value and t > after)

    def tool(self, t):
        return kinematics.tool_point_world(self.base, self.yaw, self.sdk(t))

    def head_yaw(self, t, wrist=False):
        yaw = self.yaw + kinematics.motor_angles(*self.sdk(t))[0] - 90.0
        return yaw + (self.wrist(t) - 90.0 if wrist else 0.0)


def rot_z(v, deg):
    a = math.radians(deg)
    return (v[0] * math.cos(a) - v[1] * math.sin(a), v[0] * math.sin(a) + v[1] * math.cos(a), v[2])


def add(a, b):
    return tuple(x + y for x, y in zip(a, b))


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def half_x(yaw):
    a = math.radians(yaw)
    return abs(math.cos(a)) * HX / 2 + abs(math.sin(a)) * HY / 2


class Cycle:
    """Phase 1 of the cell: holder from the supply, PCB from the tray, assembly out on belt 2."""

    def __init__(self):
        cell = self.cell = build_scene.layout()
        robots = cell["robots"]
        a1 = ArmTrack(robots["uarm1"], waypoints(sequences.ARM1_SEQ1)[-1])
        a2 = ArmTrack(robots["uarm2"], waypoints(sequences.ARM2_SEQ2)[-1])
        a3 = ArmTrack(robots["uarm3"], waypoints(sequences.ARM3_SEQ1)[-1])
        self.arms = {"arm1": a1, "arm2": a2, "arm3": a3}
        belt_z = build_scene.BELT_TOP + HZ / 2
        sensors = cell["sensors"]

        end1 = a1.run(sequences.ARM1_SEQ1, 0.6)
        c1 = waypoints(sequences.ARM1_SEQ1, "catch")
        self.pick1 = a1.arrival(c1[0])
        self.release1 = a1.arrival(c1[2], self.pick1) + 0.15
        self.grip1 = (sub(cell["holder"], a1.tool(self.pick1)), a1.head_yaw(self.pick1))
        centre, yaw = self._held(a1, self.release1, self.grip1, False)
        self.drop1 = (centre, (centre[0], centre[1], belt_z), yaw)
        start = self.release1 + 0.25
        self.belt1 = (start, start + (sensors["S2"][0] - half_x(yaw) - centre[0]) / BELT_SPEED)

        a2.run(sequences.ARM2_SEQ1, self.belt1[1] + 0.2)
        self.grab2 = a2.event("gripper", True)
        self.hold2 = a2.t
        centre, yaw = self._on_belt1(self.grab2)
        self.grip2 = (sub(centre, a2.tool(self.grab2)), a2.head_yaw(self.grab2, wrist=True), yaw)

        end3 = a3.run(sequences.ARM3_SEQ1, self.hold2 + 0.2)
        c3 = waypoints(sequences.ARM3_SEQ1, "catch")
        self.pick3 = a3.arrival(c3[0])
        self.drop3 = a3.arrival(c3[2], self.pick3) + 0.15
        self.grip3 = (sub(cell["pcb"], a3.tool(self.pick3)), a3.head_yaw(self.pick3))

        end2 = a2.run(sequences.ARM2_SEQ2, self.drop3 + 0.5)
        self.release2 = a2.event("gripper", False, self.grab2)
        centre, yaw = self._held(a2, self.release2, self.grip2[:2], True)
        yaw += self.grip2[2]
        self.drop2 = (centre, (centre[0], centre[1], belt_z), yaw)
        start = self.release2 + 0.25
        self.belt2 = (start, start + (centre[0] - sensors["S4"][0] - half_x(yaw)) / BELT_SPEED)
        self.gone = self.belt2[1] + 0.6
        self.T = round(max(self.gone + 0.7, end1, end2, end3) + 0.3, 1)

    @staticmethod
    def _held(arm, t, grip, wrist):
        """Pick-as-is: the part keeps its offset to the tool and turns with the tool head."""
        offset, head0 = grip
        turn = arm.head_yaw(t, wrist) - head0
        return add(arm.tool(t), rot_z(offset, turn)), turn

    @staticmethod
    def _settle(drop, t, t_release, shift):
        released, resting, yaw = drop
        z = released[2] + (resting[2] - released[2]) * ease((t - t_release) / 0.15)
        return (resting[0] + shift, resting[1], z), yaw

    def _on_belt1(self, t):
        b0, b1 = self.belt1
        return self._settle(self.drop1, t, self.release1, BELT_SPEED * (min(max(t, b0), b1) - b0))

    def holder(self, t):
        """Holder centre (m), yaw (deg) and opacity."""
        opacity = min(1.0, t / 0.3) * (1.0 - ease((t - self.gone) / 0.5))
        if t < self.pick1:
            return self.cell["holder"], 0.0, opacity
        if t < self.release1:
            return (*self._held(self.arms["arm1"], t, self.grip1, False), opacity)
        if t < self.grab2:
            return (*self._on_belt1(t), opacity)
        if t < self.release2:
            centre, turn = self._held(self.arms["arm2"], t, self.grip2[:2], True)
            return centre, self.grip2[2] + turn, opacity
        b0, b1 = self.belt2
        return (*self._settle(self.drop2, t, self.release2, -BELT_SPEED * (min(max(t, b0), b1) - b0)), opacity)

    def pcb(self, t):
        if t < self.pick3:
            return self.cell["pcb"], 0.0, min(1.0, t / 0.3)
        if t < self.drop3:
            return (*self._held(self.arms["arm3"], t, self.grip3, False), 1.0)
        start, start_yaw = self._held(self.arms["arm3"], self.drop3, self.grip3, False)
        holder, holder_yaw, opacity = self.holder(t)
        seated = add(holder, (0.0, 0.0, HZ / 2 + PZ / 2))
        return lerp(start, seated, ease((t - self.drop3) / 0.2)), start_yaw + holder_yaw - self.holder(self.drop3)[1], \
            opacity

    def sensor_on(self, name, t):
        (cx, cy, cz), yaw, opacity = self.holder(t)
        if opacity < 0.5:
            return False
        sx, sy, sz = self.cell["sensors"][name]
        a = math.radians(yaw)
        half_y = abs(math.sin(a)) * HX / 2 + abs(math.cos(a)) * HY / 2
        return abs(cx - sx) <= half_x(yaw) and cy - half_y < sy and cz - HZ / 2 <= sz <= cz + HZ / 2

    def belt_on(self, index, t):
        b0, b1 = self.belt1 if index == 1 else self.belt2
        return b0 <= t < b1

    def tool_on(self, name, t):
        if name == "arm1":
            return self.pick1 - 0.05 <= t < self.release1
        if name == "arm2":
            return self.grab2 <= t < self.release2
        return self.pick3 - 0.05 <= t < self.drop3

    def servo(self, name, t):
        arm = self.arms[name]
        values = list(kinematics.motor_angles(*arm.sdk(t)))
        return values + [arm.wrist(t)] if name == "arm2" else values

    def captions(self):
        a2, a3 = self.arms["arm2"], self.arms["arm3"]
        return [
            (0.0, "Arm 1 picks a holder from the supply with its vacuum cup"),
            (self.release1 - 0.3, "Released on belt 1 - light barrier S1 sees it and the belt starts"),
            (self.belt1[1], "S2 stops the holder under arm 2 and the gripper closes"),
            (self.grab2 + 1.0, "Arm 2 turns its wrist and presents the holder"),
            (a3.arrival(waypoints(sequences.ARM3_SEQ1)[0], self.hold2) - 0.2, "Arm 3 picks a PCB from the tray"),
            (self.drop3 - 0.3, "Vacuum off: the PCB drops onto the holder"),
            (a2.event("wrist", 0, self.drop3) - 0.1, "Arm 2 sets the assembly on belt 2 - S3 starts the belt"),
            (self.belt2[1] - 0.2, "S4 stops the belt - cycle complete"),
        ]


