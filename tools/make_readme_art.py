# Isometric view of the cell
# ---------------------------------------------------------------------------------------------
AZ, EL = math.radians(25.0), math.radians(32.0)
CA, SA, CE, SE = math.cos(AZ), math.sin(AZ), math.cos(EL), math.sin(EL)
VIEW = {"s": 1.0, "ox": 0.0, "oy": 0.0}


def uv(p):
    depth = -p[0] * SA + p[1] * CA
    return p[0] * CA + p[1] * SA, p[2] * CE + depth * SE


def project(p):
    u, v = uv(p)
    return VIEW["ox"] + VIEW["s"] * u, VIEW["oy"] - VIEW["s"] * v


def fit_view(points, box):
    us, vs = zip(*(uv(p) for p in points))
    x0, y0, x1, y1 = box
    s = min((x1 - x0) / (max(us) - min(us)), (y1 - y0) / (max(vs) - min(vs)))
    VIEW.update(s=s, ox=(x0 + x1) / 2 - s * (min(us) + max(us)) / 2, oy=(y0 + y1) / 2 + s * (min(vs) + max(vs)) / 2)


def iso_box(x, y, z, colours):
    """Visible faces of an axis-aligned box: front (-y), right (+x), top."""
    (x0, x1), (y0, y1), (z0, z1) = x, y, z
    faces = ([(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)],
             [(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)],
             [(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)])
    return [Item("shape", [[project(p) for p in face]], fill=colour) for face, colour in zip(faces, colours[1:] + colours[:1])]


def ellipse(centre, radius, n=40):
    return [project((centre[0] + radius * math.cos(2 * math.pi * i / n), centre[1] + radius * math.sin(2 * math.pi * i / n),
                     centre[2])) for i in range(n)]


def cylinder(centre, radius, height, side, top, rim):
    bottom = ellipse(centre, radius)
    upper = ellipse((centre[0], centre[1], centre[2] + height), radius)
    left = min(range(len(bottom)), key=lambda i: bottom[i][0])
    right = max(range(len(bottom)), key=lambda i: bottom[i][0])
    return [Item("shape", [bottom], fill=side), Item("shape", [[upper[left], bottom[left], bottom[right], upper[right]]],
                                                     fill=side), Item("shape", [upper], fill=top, stroke=rim, width=1)]


def corners(centre, yaw, size, scale=1.0, dz=0.0):
    sx, sy, _ = size
    return [project(add(centre, (*rot_z((dx * sx * scale / 2, dy * sy * scale / 2, 0.0), yaw)[:2], dz)))
            for dx, dy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]


def part_faces(centre, yaw, size):
    """Bottom and four sides (one colour, so painter order does not matter) plus the top of a yawed box."""
    low, high = corners(centre, yaw, size, dz=-size[2] / 2), corners(centre, yaw, size, dz=size[2] / 2)
    sides = [low] + [[low[i], low[(i + 1) % 4], high[(i + 1) % 4], high[i]] for i in range(4)]
    return [ccw(face) for face in sides], [high]


def ccw(poly):
    area = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(poly, poly[1:] + poly[:1]))
    return poly if area >= 0 else poly[::-1]


class BeltMarks:
    """Belt surface marks: one static path moved by a translate animation and clipped to the belt."""

    def __init__(self, cycle, index):
        self.index = index
        self.y0, self.y1 = build_scene.CONVEYORS[f"Conveyor{index}"]["y"]
        self.run = cycle.belt1 if index == 1 else cycle.belt2
        self.sign = 1.0 if index == 1 else -1.0
        travel = BELT_SPEED * (self.run[1] - self.run[0])
        self.pitch = travel / max(1, round(travel / 0.03))
        x0, x1 = build_scene.BELT_X
        first = x0 - travel if self.sign > 0 else x0
        self.xs = [first + i * self.pitch for i in range(int((x1 - x0 + travel) / self.pitch) + 1)]

    def shift(self, t):
        b0, b1 = self.run
        return self.sign * BELT_SPEED * (min(max(t, b0), b1) - b0)

    def _stripe(self, x):
        z = build_scene.BELT_TOP
        return [project((x, self.y0 + 0.004, z)), project((x, self.y1 - 0.004, z))]

    def svg(self, frames, dur):
        x0, x1 = build_scene.BELT_X
        z = build_scene.BELT_TOP
        clip = [project(p) for p in ((x0, self.y0, z), (x1, self.y0, z), (x1, self.y1, z), (x0, self.y1, z))]
        origin = project((0.0, 0.0, 0.0))
        moves = []
        for t in frames:
            px, py = project((self.shift(t), 0.0, 0.0))
            moves.append(f"{px - origin[0]:.1f},{py - origin[1]:.1f}")
        return (f'<clipPath id="belt{self.index}"><path d="{path_d("shape", [clip])}"/></clipPath>'
                f'<g clip-path="url(#belt{self.index})"><g>{smil("", moves, dur, translate=True)}'
                f'<path d="{path_d("line", [self._stripe(x) for x in self.xs])}" stroke="#ffffff" stroke-opacity=".16" '
                'stroke-width="1.1"/></g></g>')

    def pil(self, draw, t, k):
        x0, x1 = build_scene.BELT_X
        for x in self.xs:
            x += self.shift(t)
            if x0 <= x <= x1:
                draw.line([(a * k, b * k) for a, b in self._stripe(x)], fill=mix("#ffffff", BG, 0.16), width=1)


POSES = {}


def arm_pose(cycle, name, t):
    key = (name, round(t, 5))
    if key not in POSES:
        arm = cycle.arms[name]
        motors = kinematics.motor_angles(*arm.sdk(t))
        if motors is None:
            raise ValueError(f"{name} unreachable at t={t:.2f}: {arm.sdk(t)}")
        j1, j2, j6 = kinematics.joints_from_motors(*motors)
        plane = kinematics.solve_linkage(j2, j6)["points"]
        c, s = math.cos(math.radians(j1)), math.sin(math.radians(j1))

        def world(x, z):
            return kinematics.place(arm.base, arm.yaw, (x * c, x * s, z))

        pts = {k: world(*v) for k, v in plane.items()}
        pts["corner"] = world(plane["tool"][0], plane["wrist"][1])
        pts["turret"] = world(0.0, kinematics.BASE_HEIGHT)
        POSES[key] = pts
    return POSES[key]


def linkage_items(pose, scale=1.0, tool_colour=None, main="#e8e8e8"):
    """Shared arm drawing: rods, rear plate, main links, level effector, pins and the driven shoulder."""
    def get(t):
        return pose(t)

    def links(t):
        p = get(t)
        return [[p["shoulder"], p["elbow"]], [p["pin_b"], p["elbow"], p["wrist"]]]

    def effector(t):
        p = get(t)
        return [[p["joint9"], p["wrist"], p["corner"], p["tool"]]]

    def rods(t):
        p = get(t)
        return [[p["rear_pivot"], p["pin_a"]], [p["shoulder"], p["crank_pin"], p["pin_b"]], [p["pin_c"], p["joint9"]]]

    def pins(t):
        p = get(t)
        return [[p[k]] for k in ("elbow", "wrist", "pin_a", "pin_b", "pin_c", "joint9", "crank_pin", "rear_pivot")]

    return [
        Item("line", rods, stroke="#8a8a8a", width=2.4 * scale),
        Item("shape", lambda t: [[get(t)["elbow"], get(t)["pin_a"], get(t)["pin_c"]]], fill="#575757"),
        Item("line", links, stroke="#000000", width=10 * scale),
        Item("line", links, stroke=main, width=6 * scale),
        Item("line", effector, stroke="#000000", width=8 * scale),
        Item("line", effector, stroke="#c8c8c8", width=4.2 * scale),
        Item("dots", pins, stroke="#101010", width=4.2 * scale),
        Item("dots", lambda t: [[get(t)["shoulder"]]], stroke="#000000", width=10 * scale),
        Item("dots", lambda t: [[get(t)["shoulder"]]], stroke=GREEN, width=6.5 * scale),
        Item("dots", lambda t: [[get(t)["tool"]]], stroke=GREY4, width=7.5 * scale, color=tool_colour),
    ]


def arm_items(cycle, name):
    def pose(t):
        return {k: project(p) for k, p in arm_pose(cycle, name, t).items()}

